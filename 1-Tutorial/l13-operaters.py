# Arithmetic Operators
"""
____________________________________________
 Operator | Name               | Example    |
__________|____________________|____________|
   +      |   Addition         |   x + y    |
   -      |   Subtraction      |   x - y    |
   *      |   Multiplication   |   x * y    |
   /      |   Division         |   x / y    |
   %      |   Modulus          |   x % y    |
   **     |   Exponentiation   |   x ** y   |
   //     |   Floor Division   |   x // y   |
____________________________________________
"""
x = 5
y = 3
print("x:3 + y:5 = ", x + y)
x = 5
y = 3
